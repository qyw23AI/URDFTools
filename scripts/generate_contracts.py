#!/usr/bin/env python3
"""Generate TS from Pydantic JSON Schema; fail closed on unknown constructs."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'python'))
from urdftools.core.models import RobotDocument, RobotSnapshot, EditTransaction, OperationResult, ProjectManifest


def ts_type(schema):
    if '$ref' in schema:
        return schema['$ref'].split('/')[-1]
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(v) for v in schema['enum'])
    for union in ('anyOf', 'oneOf'):
        if union in schema:
            return '(' + ' | '.join(ts_type(s) for s in schema[union]) + ')'
    kind = schema.get('type')
    if kind == 'object':
        if schema.get('additionalProperties') is not False:
            raise ValueError('open object unsupported')
        required = schema.get('required', [])
        return '{\n' + '\n'.join('  readonly ' + json.dumps(k) + ('' if k in required else '?') + ': ' + ts_type(v) + ';' for k, v in schema.get('properties', {}).items()) + '\n}'
    if kind == 'array':
        if 'prefixItems' in schema:
            return 'readonly [' + ', '.join(ts_type(v) for v in schema['prefixItems']) + ']'
        return 'ReadonlyArray<' + ts_type(schema['items']) + '>'
    if kind in ('string', 'number', 'integer', 'boolean', 'null'):
        return {'integer': 'number'}.get(kind, kind)
    raise ValueError(f'unsupported schema: {schema}')


def generated():
    definitions = {}
    for model in (RobotDocument, RobotSnapshot, EditTransaction, OperationResult, ProjectManifest):
        schema = model.model_json_schema(mode='validation')
        for key, definition in schema.pop('$defs', {}).items():
            if key in definitions and definitions[key] != definition:
                raise ValueError(f'conflicting definition {key}')
            definitions[key] = definition
        definitions[model.__name__] = schema
    bundle = {'$schema': 'https://json-schema.org/draft/2020-12/schema', '$defs': definitions,
              'oneOf': [{'$ref': '#/$defs/' + m} for m in ('RobotDocument', 'RobotSnapshot', 'EditTransaction', 'OperationResult', 'ProjectManifest')]}
    types = '// Generated by scripts/generate_contracts.py; do not edit.\n// Runtime graph, hash, SI and provenance invariants are validated by Python.\n'
    types += '\n\n'.join('export type ' + name + ' = ' + ts_type(definition) + ';' for name, definition in sorted(definitions.items())) + '\n'
    return {'schema.json': json.dumps(bundle, ensure_ascii=False, indent=2, sort_keys=True) + '\n', 'index.ts': types}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, content in generated().items():
        target = ROOT / 'packages/contracts' / name
        if args.check:
            if not target.exists() or target.read_text() != content:
                raise SystemExit(f'contract drift: {target}')
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
    print('Pydantic/JSON Schema/TypeScript contracts consistent')


if __name__ == '__main__':
    main()
